CODE_RX = r"(?P<code>УК|УПК|КоАП|КАП|ТК|ПДД|ГК|Конституци\w*)"
CITE = re.compile(
    r"(?:(?:ч\.|часть|части|частью)\s*\d+\s*)?"
    r"(?P<kind>ст\.|стать[яиеюй]|статьей|статьёй|п\.|пункт[а-я]*|пп\.)\s*(?P<num>\d+(?:\.\d+)*)(?!\d)"
    rf"(?:\s*(?:ч\.\s*\d+\s*)?(?:РО\s*)?{CODE_RX}\b)?", re.I)


def norm(s):
    return str(s or "").replace("ё", "е").replace("Ё", "Е")


def expand_query(q):
    """«ДМ по УК» → «ДМ по УК dm deathmatch … уголовный кодекс»: поиск по словам сокращений не понимает."""
    words = re.findall(r"[a-zа-яё]+", norm(q).lower())
    extra = [ABBR[w] for w in words if ABBR.get(w)]
    return (q + " " + " ".join(extra)).strip() if extra else q


def citations(text):
    """Все ссылки на статьи/пункты: [{raw, kind: article|point, num, code}] (без повторов)."""
    out, seen = [], set()
    for m in CITE.finditer(norm(text)):
        kind = "article" if m.group("kind").lower().startswith("ст") else "point"
        code = (m.group("code") or "").lower()
        code = "конституци" if code.startswith("конституци") else code
        key = (kind, m.group("num"), code)
        if key in seen:
            continue
        seen.add(key)
        out.append({"raw": m.group(0).strip(), "kind": kind, "num": m.group("num"), "code": code})
    return out


def title_fits(code, title):
    """Подходит ли документ под код из ссылки («УК» — уголовный кодекс, но не уголовно-процессуальный)."""
    if code not in CODES:
        return True
    want, bad = CODES[code]
    t = norm(title).lower()
    return any(w in t for w in want) and not any(b in t for b in bad)


def _docs_for(code, docs):
    sel = [d for d in docs if title_fits(code, d.get("title") or "")]
    return sel or docs  # документа с таким названием нет — ищем по всей базе


def exists(c, docs):
    """Есть ли статья/пункт в базе. «ст. 12» засчитываем и при «Статья 12.1» (часть нумерации)."""
    n = re.escape(c["num"])
    pats = [rf"(?:стать[яи]|ст\.)\s*{n}(?!\d)", rf"(?m)^\s*{n}(?:\.(?!\d)|\s|\)|$)"]
    if c["kind"] == "point":
        pats += [rf"(?:п\.|пункт\w*)\s*{n}(?!\d)", rf"(?m)^\s*{n}\.\d"]
    rx = [re.compile(p, re.I) for p in pats]
    return any(r.search(norm(d.get("content") or d.get("text") or "")) for d in _docs_for(c["code"], docs) for r in rx)


def verify(text, docs):
    """Самопроверка ответа юриста: ссылки, которых нет в базе, помечаются ⚠️. → (текст, [непроверенные raw])."""
    missing = [c for c in citations(text) if not exists(c, docs)]
    if not missing:
        return text, []
    out = text
    for c in missing:  # raw найден в тексте с «е» вместо «ё» — ищем в исходном с любой из двух
        pat = re.escape(c["raw"]).replace("е", "[её]").replace("Е", "[ЕЁ]")
        out = re.sub(rf"(?<![\w.]){pat}(?![\d])", lambda m: m.group(0) + " ⚠️", out)
    return out, [c["raw"] for c in missing]


def asked_refs(q):
    """Номера статей/пунктов, о которых прямо спросили («что за ст. 12.3 УК») — такие куски идут ИИ первыми."""
    return citations(q)


ART_HEAD = re.compile(r"(?im)^\s*стать[яи]\s+(\d+(?:\.\d+)*)")
POINT_HEAD = re.compile(r"(?m)^\s*(\d+(?:\.\d+)+)\.?\s")


def article_map(text):
    """Текст закона → {номер статьи/пункта: текст}. Статей нет — режем по пунктам «1.2.»."""
    t = norm(text)
    heads = list(ART_HEAD.finditer(t)) or list(POINT_HEAD.finditer(t))
    out = {}
    for i, m in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(t)
        body = " ".join(t[m.start():end].split())
        out.setdefault(m.group(1), body)
    return out


def _nat(n):
    return [int(x) for x in n.split(".") if x.isdigit()]


def diff_articles(old, new):
    """Что поменялось в законе: (добавлены, удалены, изменены) — списки номеров по порядку."""
    a, b = article_map(old), article_map(new)
    added = sorted((k for k in b if k not in a), key=_nat)
    removed = sorted((k for k in a if k not in b), key=_nat)
    changed = sorted((k for k in b if k in a and a[k] != b[k]), key=_nat)
    return added, removed, changed


def diff_line(title, old, new):
    added, removed, changed = diff_articles(old, new)
    parts = []
    for label, xs in (("изменены", changed), ("добавлены", added), ("удалены", removed)):
        if xs:
            parts.append(f"{label}: " + ", ".join(xs[:12]) + (f" и ещё {len(xs) - 12}" if len(xs) > 12 else ""))
    return f"«{title}» — " + ("; ".join(parts) if parts else "текст поправлен (без смены номеров статей)")


